// Generate 36 realistic historical sensor readings across machines
export const INITIAL_SENSOR_READINGS: SensorReading[] = (() => {
  const list: SensorReading[] = [];
  const baseTime = new Date('2026-10-30T14:00:00Z').getTime();

  INITIAL_MACHINES.forEach((m, idx) => {
    for (let step = 0; step < 3; step++) {
      const offsetMinutes = (idx * 3 + step) * 10;
      const t = new Date(baseTime + offsetMinutes * 60 * 1000).toISOString();
      const delta = (step - 1) * 1.8;
      const temp = Number((m.temperature + delta).toFixed(1));
      const vib = Number(Math.max(0.6, m.vibration + delta * 0.18).toFixed(2));
      const press = Math.round(m.pressure + delta * 1.4);
      const evalRes = evaluateMachineRisk(
        {
          ...m,
          temperature: temp,
          vibration: vib,
          pressure: press,
        },
        DEFAULT_RISK_THRESHOLDS
      );

      list.push({
        id: `SR-${1000 + list.length + 1}`,
        machineId: m.id,
        timestamp: t,
        temperature: temp,
        vibration: vib,
        pressure: press,
        runningHours: Math.max(100, m.runningHours - (2 - step) * 4),
        riskScore: evalRes.riskScore,
      });
    }
  });

  return list;
})();

